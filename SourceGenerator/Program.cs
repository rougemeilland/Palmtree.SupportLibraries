                        sourceWriter.WriteLine($"                sumv = sumv2 + v;");
                        sourceWriter.WriteLine($"                overflowTracking |= {GetOverflowTrackingVector(sign, vectorBitLength, "sumv2", "v", "sumv")};");
                        sourceWriter.WriteLine();
                    }

                    sourceWriter.WriteLine($"                if ((overflowTracking & overflowTestVector) != Vector{vectorBitLength}<ELEMENT_T>.Zero)");
                    sourceWriter.WriteLine($"                    throw new OverflowException();");
                    sourceWriter.WriteLine();
                    sourceWriter.WriteLine($"                offset += (UInt32)Vector{vectorBitLength}<ELEMENT_T>.Count * {n}u;");
