                        sourceWriter.WriteLine($"                {(count == 0 ? "var " : "")}overflowTracking {(count == 0 ? "=" : "|=")} {GetOverflowTrackingVector(sign, vectorBitLength, "sumv", "v", "sumv2")};");
                        sourceWriter.WriteLine();
