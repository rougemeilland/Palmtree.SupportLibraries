            static void OutputGetWidthTypeMethod(TextWriter sourceWriter, ReadOnlySpan<String> charAttributes)
            {
                var segments = new List<(Int32 startOfCodePoint, Int32 endOfCodePoint, String width)>();
                for (var codePoint = 0; codePoint < charAttributes.Length;)
                {
                    var width = charAttributes[codePoint];
                    var length = 1;
                    while (codePoint + length < charAttributes.Length && width == charAttributes[codePoint + length])
                        ++length;
                    segments.Add((codePoint, codePoint + length - 1, width));
                    codePoint += length;
                }

                if (segments[0].startOfCodePoint != 0)
                    throw new Exception();
                if (segments[^1].endOfCodePoint != charAttributes.Length - 1)
                    throw new Exception();
                for (var index = 0; index < segments.Count - 1; ++index)
                {
                    if (segments[index].endOfCodePoint + 1 != segments[index + 1].startOfCodePoint)
                        throw new Exception();
                    if (String.Equals(segments[index].width, segments[index + 1].width, StringComparison.Ordinal))
                        throw new Exception();
                }

                for (var index = 0; index < segments.Count; ++index)
                {
                    var (startOfCodePoint, endOfCodePoint, width) = segments[index];
                    for (var codePoint = startOfCodePoint; codePoint <= endOfCodePoint; ++codePoint)
                    {
                        if (!String.Equals(width, charAttributes[codePoint], StringComparison.Ordinal))
                            throw new Exception();
                    }
                }

                sourceWriter.WriteLine("        private static EastAsianWidthType GetWidthType(Int32 codePoint)");
                sourceWriter.WriteLine("        {");
                OutputSegments(sourceWriter, "            ", segments.ToArray());
                sourceWriter.WriteLine("        }");
                sourceWriter.WriteLine();
                sourceWriter.WriteLine("#if DEBUG");
                sourceWriter.WriteLine("        private static void DoTest()");
                sourceWriter.WriteLine("        {");
                for (var index = 0; index < segments.Count; ++index)
                {
                    sourceWriter.WriteLine($"            for (var codePoint = 0x{segments[index].startOfCodePoint:x8}; codePoint <= 0x{segments[index].endOfCodePoint:x8}; ++codePoint)");
                    sourceWriter.WriteLine($"                Validation.Assert(GetWidthType(codePoint) == EastAsianWidthType.{segments[index].width});");
                }

                sourceWriter.WriteLine("        }");
                sourceWriter.WriteLine("#endif");

                static void OutputSegments(TextWriter sourceWriter, String indent, ReadOnlySpan<(Int32 startOfCodePoint, Int32 endOfCodePoint, String width)> segments)
                {
                    if (segments.Length <= 0)
                    {
                        throw new Exception();
                    }
                    else if (segments.Length == 1)
                    {
                        OutputAssertion(sourceWriter, indent, segments[0].startOfCodePoint, segments[0].endOfCodePoint);
                        sourceWriter.WriteLine(indent + $"return EastAsianWidthType.{segments[0].width};");
                    }
                    else if (segments.Length == 2)
                    {
                        if (String.Equals(segments[0].width, segments[1].width, StringComparison.Ordinal))
                            throw new Exception();
                        OutputAssertion(sourceWriter, indent, segments[0].startOfCodePoint, segments[1].endOfCodePoint);
                        sourceWriter.WriteLine($"{indent}return codePoint < 0x{segments[1].startOfCodePoint:x8} ? EastAsianWidthType.{segments[0].width} : EastAsianWidthType.{segments[1].width};");
                    }
                    else
                    {
                        var startOfCodePoint = segments[0].startOfCodePoint;
                        var endOfCodePoint = segments[^1].endOfCodePoint;
                        var middleOfCodePoint = (startOfCodePoint + endOfCodePoint + 1) / 2;
                        var indexOfMiddleSegment = FindSegment(segments, middleOfCodePoint);
                        if (indexOfMiddleSegment == 0)
                        {
                            // 中央のコードポイントが最初のセグメントに属している場合
                            sourceWriter.WriteLine($"{indent}if (codePoint < 0x{segments[1].startOfCodePoint:x8})");
                            sourceWriter.WriteLine($"{indent}{{");
                            OutputAssertion(sourceWriter, $"{indent}    ", segments[0].startOfCodePoint, segments[0].endOfCodePoint);
                            sourceWriter.WriteLine($"{indent}    return EastAsianWidthType.{segments[0].width};");
                            sourceWriter.WriteLine($"{indent}}}");
                            sourceWriter.WriteLine($"{indent}else");
                            sourceWriter.WriteLine($"{indent}{{");
                            OutputSegments(sourceWriter, $"{indent}    ", segments[1..]);
                            sourceWriter.WriteLine($"{indent}}}");
                        }
                        else if (indexOfMiddleSegment == segments.Length - 1)
                        {
                            // 中央のコードポイントが最後のセグメントに属している場合
                            sourceWriter.WriteLine($"{indent}if (codePoint < 0x{segments[^1].startOfCodePoint:x8})");
                            sourceWriter.WriteLine($"{indent}{{");
                            OutputSegments(sourceWriter, $"{indent}    ", segments[..^1]);
                            sourceWriter.WriteLine($"{indent}}}");
                            sourceWriter.WriteLine($"{indent}else");
                            sourceWriter.WriteLine($"{indent}{{");
                            OutputAssertion(sourceWriter, $"{indent}    ", segments[^1].startOfCodePoint, segments[^1].endOfCodePoint);
                            sourceWriter.WriteLine($"{indent}    return EastAsianWidthType.{segments[^1].width};");
                            sourceWriter.WriteLine($"{indent}}}");
                        }
                        else
                        {
                            // 中央のコードポイントが属しているセグメントが最初と最後の何れでもない場合
                            if (middleOfCodePoint < (segments[indexOfMiddleSegment].startOfCodePoint + segments[indexOfMiddleSegment].endOfCodePoint + 1) / 2)
                            {
                                // 中央のコードポイントが属しているセグメントにおいて、中央のコードポイントが前方寄りにある場合
                                sourceWriter.WriteLine($"{indent}if (codePoint < 0x{segments[indexOfMiddleSegment].startOfCodePoint:x8})");
                                sourceWriter.WriteLine($"{indent}{{");
                                OutputSegments(sourceWriter, $"{indent}    ", segments[..indexOfMiddleSegment]);
                                sourceWriter.WriteLine($"{indent}}}");
                                sourceWriter.WriteLine($"{indent}else");
                                sourceWriter.WriteLine($"{indent}{{");
                                OutputSegments(sourceWriter, $"{indent}    ", segments[indexOfMiddleSegment..]);
                                sourceWriter.WriteLine($"{indent}}}");
                            }
                            else
                            {
                                // 中央のコードポイントが属しているセグメントにおいて、中央のコードポイントが後方寄りにある場合
                                sourceWriter.WriteLine($"{indent}if (codePoint < 0x{segments[indexOfMiddleSegment + 1].startOfCodePoint:x8})");
                                sourceWriter.WriteLine($"{indent}{{");
                                OutputSegments(sourceWriter, $"{indent}    ", segments[..(indexOfMiddleSegment + 1)]);
                                sourceWriter.WriteLine($"{indent}}}");
                                sourceWriter.WriteLine($"{indent}else");
                                sourceWriter.WriteLine($"{indent}{{");
                                OutputSegments(sourceWriter, $"{indent}    ", segments[(indexOfMiddleSegment + 1)..]);
                                sourceWriter.WriteLine($"{indent}}}");
                            }
                        }
                    }

                    static Int32 FindSegment(ReadOnlySpan<(Int32 startOfCodePoint, Int32 endOfCodePoint, String width)> segments, Int32 codePoint)
                    {
                        if (segments.Length <= 0)
                            throw new Exception();
                        if (codePoint < segments[0].startOfCodePoint)
                            throw new Exception();
                        if (codePoint > segments[^1].endOfCodePoint)
                            throw new Exception();

                        for (var index = 0; index < segments.Length; ++index)
                        {
                            if (codePoint <= segments[index].endOfCodePoint)
                                return index;
                        }

                        throw new Exception();
                    }

                    static void OutputAssertion(TextWriter writer, String indent, Int32 start, Int32 end)
                    {
                        writer.WriteLine("#if DEBUG");

                        if (start > end)
                            throw new Exception();
                        else if (start == end)
                            writer.WriteLine($"{indent}Validation.Assert(codePoint == 0x{start:x8});");
                        else if (start + 1 == end)
                            writer.WriteLine($"{indent}Validation.Assert(codePoint is 0x{start:x8} or 0x{end:x8});");
                        else
                            writer.WriteLine($"{indent}Validation.Assert(codePoint is >= 0x{start:x8} and <= 0x{end:x8});");

                        writer.WriteLine("#endif");
                    }
                }
            }
        }

